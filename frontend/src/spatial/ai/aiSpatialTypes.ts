import type { Point2D } from '../parametric/parametricTypes';
import type { SemanticRelationship, SemanticZone } from '../../types/scene';

/**
 * Versioned schema identifier for the Spatial Context format.
 */
export const SPATIAL_CONTEXT_SCHEMA_VERSION = 1;

/**
 * Compact representation of a wall segment for AI spatial reasoning.
 */
export interface SpatialWallDescriptor {
  id: string;
  startPoint: Point2D;
  endPoint: Point2D;
  lengthMeters: number;
  cardinalOrientation: 'north' | 'south' | 'east' | 'west' | 'slanted';
  interiorNormal: Point2D; // 2D unit vector pointing into room
}

/**
 * Compact representation of an architectural opening (door / window).
 */
export interface SpatialOpeningDescriptor {
  id: string;
  wallId: string;
  type: 'door' | 'window';
  center: Point2D;
  widthMeters: number;
  heightMeters: number;
  accessPoint?: Point2D; // Landing coordinate for pedestrian entry
  swing?: string;
  isPedestrianPortal: boolean;
}

/**
 * Summary of an unfilled semantic socket on a placed furniture anchor.
 */
export interface AvailableSocketDescriptor {
  anchorObjectId: string;
  anchorName: string;
  socketId: string;
  socketName: string;
  worldPosition: [number, number, number];
  facingDirection: [number, number, number];
  allowedCategories: string[];
}

/**
 * Compact spatial context representation of a placed furniture item.
 */
export interface SpatialObjectDescriptor {
  id: string;
  assetId: string;
  name: string;
  category: string;
  position: [number, number, number];
  rotationEuler: [number, number, number];
  scale: [number, number, number];
  dimensions: [number, number, number];
  color?: string;
  isAnchor: boolean;
  hasRelationships: boolean;
}

/**
 * Walkability and circulation summary for AI context.
 */
export interface SpatialWalkabilitySummary {
  walkabilityScore: number; // 0-100
  isRoomPassable: boolean;
  accessibleRatio: number; // 0.0 - 1.0
  unblockedEntranceCount: number;
  blockedDoorIds: string[];
  narrowestPassageMeters: number;
  walkableAreaRatio: number;
}

/**
 * Complete, versioned Spatial Context schema supplied to AI reasoning models.
 * Excludes raw vertex buffers, mesh data, and large textures to ensure low token overhead.
 */
export interface SpatialContext {
  schemaVersion: number;
  room: {
    dimensions: [number, number, number]; // [width, height, length]
    areaSqm: number;
    footprint: Point2D[];
    isParametric: boolean;
    wallCount: number;
    walls: SpatialWallDescriptor[];
    openings: SpatialOpeningDescriptor[];
  };
  placedObjects: SpatialObjectDescriptor[];
  relationships: SemanticRelationship[];
  availableSockets: AvailableSocketDescriptor[];
  walkability?: SpatialWalkabilitySummary;
  zones?: SemanticZone[];
  usableSpace: {
    totalAreaSqm: number;
    occupiedAreaSqm: number;
    freeAreaRatio: number;
  };
}

/**
 * Structured validation issue returned by the deterministic spatial engine.
 */
export interface SpatialValidationIssue {
  code: 
    | 'ROOM_BOUNDARY_BREACH'
    | 'OBB_COLLISION'
    | 'CLEARANCE_VIOLATION'
    | 'GROUNDING_ERROR'
    | 'DOOR_BLOCKED'
    | 'UNREACHABLE_FURNITURE'
    | 'NARROW_PASSAGE'
    | 'SOCKET_INCOMPATIBLE'
    | 'SOCKET_OCCUPIED'
    | 'SOCKET_NOT_FOUND'
    | 'INVALID_GAP'
    | 'CYCLE_DETECTED'
    | 'ZONE_PRESERVATION_BREACH'
    | 'BUDGET_EXCEEDED';
  severity: 'fatal' | 'warning' | 'info';
  objectIds: string[];
  message: string;
  location?: Point2D;
  recommendation?: string;
}

/**
 * Structured action representing a semantic socket attachment.
 */
export interface AttachToSocketAction {
  type: 'attach_to_socket';
  child_object_id: string;
  anchor_object_id: string;
  socket_id: string;
  gap_meters?: number;
  relative_yaw?: number;
}

/**
 * Structured action representing a functional zone arrangement.
 */
export interface ProposeZoneArrangementAction {
  type: 'propose_zone_arrangement';
  zone_type: 'living' | 'sleeping' | 'workspace' | 'dining';
  intent: string;
  requirements?: {
    required_categories?: string[];
    preferred_categories?: string[];
    preserve_existing_furniture?: boolean;
  };
}

/**
 * Structured validation report returned to the reasoning engine or user.
 */
export interface ValidationFeedback {
  isValid: boolean;
  hasCollisions: boolean;
  hasBoundaryBreaches: boolean;
  isBudgetCompliant: boolean;
  isRoomPassable: boolean;
  fatalErrors: SpatialValidationIssue[];
  advisoryWarnings: SpatialValidationIssue[];
}

/**
 * Candidate Layout proposal generated by AI spatial reasoning.
 */
export interface LayoutProposal {
  id: string;
  schemaVersion: number;
  userIntent: string;
  reasoningSummary: string;
  proposedActions: Array<{
    type: string;
    [key: string]: any;
  }>;
  intendedRelationships?: SemanticRelationship[];
  score?: number;
  validationFeedback?: ValidationFeedback;
}
